"""Voter registry models.

Voters are intentionally NOT ``accounts.User`` rows:

* voter credentials authenticate *voting sessions only* — they can never
  reach admin/monitoring surfaces;
* bulk registry operations (imports, exports) never touch auth tables;
* identity-side data (Voter, VoterCredential) lives in separate tables from
  ballot selections (apps.ballots) — see docs/ballot-secrecy.md.

Institutional ID alone never proves ownership: login requires a second factor
(server-issued one-time code delivered out-of-band, or credential card) as
configured per organization (``Organization``-level policy in voters.policy).
"""
from django.conf import settings
from django.core.exceptions import ValidationError
from django.core.validators import RegexValidator
from django.db import models

from apps.core.models import TimeStampedModel
from apps.orgs.models import Organization, Unit

voter_number_validator = RegexValidator(
    r"^[A-Za-z0-9._\-/]{3,40}$",
    "Allowed: letters, digits, dot, underscore, dash, slash (3–40 chars).",
)


class Voter(TimeStampedModel):
    class Status(models.TextChoices):
        ACTIVE = "active", "Active"
        FROZEN = "frozen", "Frozen (list closed)"
        WITHDRAWN = "withdrawn", "Withdrawn"
        CHALLENGED = "challenged", "Eligibility challenged"
        DISQUALIFIED = "disqualified", "Disqualified"

    organization = models.ForeignKey(
        Organization, on_delete=models.CASCADE, related_name="voters"
    )
    voter_number = models.CharField(
        max_length=40,
        validators=[voter_number_validator],
        help_text="Institutional ID / register number. Not a password.",
        db_index=True,
    )
    full_name = models.CharField(max_length=200)
    email = models.EmailField(blank=True)
    # Normalized contact for OTP delivery — never displayed in dashboards.
    phone = models.CharField(max_length=32, blank=True)
    unit = models.ForeignKey(
        Unit, null=True, blank=True, on_delete=models.SET_NULL, related_name="voters"
    )
    # Optional free-form extra units for multi-level eligibility (hall + dept)
    units = models.ManyToManyField(Unit, blank=True, related_name="voters_extra")
    status = models.CharField(
        max_length=16, choices=Status.choices, default=Status.ACTIVE, db_index=True
    )
    is_verified = models.BooleanField(
        default=False,
        help_text="Set after identity verification (OTP/card) succeeded.",
    )

    class Meta:
        ordering = ["voter_number"]
        constraints = [
            models.UniqueConstraint(
                fields=["organization", "voter_number"], name="uniq_voter_number_per_org"
            ),
        ]
        indexes = [
            models.Index(fields=["organization", "status"]),
            models.Index(fields=["organization", "unit"]),
        ]

    def __str__(self):
        return f"{self.voter_number} ({self.organization.slug})"

    def clean(self):
        if self.unit_id and self.unit.organization_id != self.organization_id:
            raise ValidationError("Unit belongs to a different organization.")


class VoterCredential(TimeStampedModel):
    """Password credential for a voter account.

    Only the hash is stored (Django PBKDF2). Import never accepts plaintext
    passwords: credentials are either (a) set by the voter through a verified
    claim flow, or (b) generated by an admin as a one-time activation code.
    """

    voter = models.OneToOneField(Voter, on_delete=models.CASCADE, related_name="credential")
    password = models.CharField(max_length=128, blank=True)  # hash only, blank = not yet claimed
    failed_attempts = models.PositiveSmallIntegerField(default=0)
    locked_until = models.DateTimeField(null=True, blank=True)
    last_login_at = models.DateTimeField(null=True, blank=True)
    activation_nonce_hash = models.CharField(max_length=128, blank=True)

    def set_password(self, raw: str):
        from django.contrib.auth.hashers import make_password

        self.password = make_password(raw)

    def check_password(self, raw: str) -> bool:
        from django.contrib.auth.hashers import check_password

        if not self.password:
            return False
        return check_password(raw, self.password)

    @property
    def is_locked(self) -> bool:
        from django.utils import timezone

        return bool(self.locked_until and self.locked_until > timezone.now())


class VoterImportBatch(TimeStampedModel):
    """Bulk import record with error report (audit + operator feedback)."""

    class Status(models.TextChoices):
        PENDING = "pending", "Pending"
        PROCESSING = "processing", "Processing"
        COMPLETED = "completed", "Completed"
        FAILED = "failed", "Failed"

    organization = models.ForeignKey(
        Organization, on_delete=models.CASCADE, related_name="voter_imports"
    )
    uploaded_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, null=True, on_delete=models.SET_NULL, related_name="+"
    )
    original_filename = models.CharField(max_length=255)
    status = models.CharField(max_length=12, choices=Status.choices, default=Status.PENDING)
    total_rows = models.PositiveIntegerField(default=0)
    imported_rows = models.PositiveIntegerField(default=0)
    rejected_rows = models.PositiveIntegerField(default=0)
    duplicate_rows = models.PositiveIntegerField(default=0)
    # Row-level error report: [{"row": 12, "error": "..."}] — contains only
    # import-file contents (voter register data), no credentials or ballots.
    error_report = models.JSONField(default=list, blank=True)

    class Meta:
        ordering = ["-created_at"]
        indexes = [models.Index(fields=["organization", "status"])]

    def __str__(self):
        return f"import {self.pk} {self.organization.slug} ({self.status})"


class EligibilityRule(TimeStampedModel):
    """Configurable per-election eligibility rule.

    A voter is eligible for an election when it belongs to the same org and
    matches ALL active rules (AND semantics), or when no rules exist
    (org-wide suffrage). Rules are frozen with the configuration hash.
    """

    class Match(models.TextChoices):
        UNIT = "unit", "Voter unit (primary or extra)"
        UNIT_TYPE = "unit_type", "Unit type of voter's primary unit"
        VERIFIED = "verified", "Identity verified"
        STATUS = "status", "Voter status is"

    election = models.ForeignKey(
        "elections.Election", on_delete=models.CASCADE, related_name="eligibility_rules"
    )
    match = models.CharField(max_length=16, choices=Match.choices, default=Match.UNIT)
    unit = models.ForeignKey(
        Unit, null=True, blank=True, on_delete=models.CASCADE, related_name="+"
    )
    unit_type = models.CharField(max_length=20, blank=True)
    status = models.CharField(max_length=16, blank=True, default="active")
    is_active = models.BooleanField(default=True, db_index=True)

    class Meta:
        indexes = [models.Index(fields=["election", "is_active"])]

    def __str__(self):
        return f"{self.election.slug}: {self.get_match_display()}"


class EligibilityDecision(TimeStampedModel):
    """Audit record for per-voter eligibility overrides/disputes."""

    class Action(models.TextChoices):
        GRANTED = "granted", "Granted"
        DENIED = "denied", "Denied"
        CHALLENGED = "challenged", "Challenged"
        RESOLVED = "resolved", "Resolved"
        WITHDRAWN = "withdrawn", "Withdrawn"

    election = models.ForeignKey(
        "elections.Election", on_delete=models.CASCADE, related_name="eligibility_decisions"
    )
    voter = models.ForeignKey(Voter, on_delete=models.CASCADE, related_name="eligibility_decisions")
    action = models.CharField(max_length=12, choices=Action.choices)
    reason = models.TextField()
    decided_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, null=True, on_delete=models.SET_NULL, related_name="+"
    )

    class Meta:
        ordering = ["-created_at"]
        indexes = [models.Index(fields=["election", "voter"])]

    def __str__(self):
        return f"{self.voter.voter_number}: {self.action}"
